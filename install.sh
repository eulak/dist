    dylib=b'@rpath/CarmowRootful.framework/CarmowRootful\x00'
    pad=(8-len(dylib)%8)%8; dylib=dylib.ljust(len(dylib)+pad,b'\x00')
    n=struct.unpack_from('<I',d,16)[0]; soc=struct.unpack_from('<I',d,20)[0]
